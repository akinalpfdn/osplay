#include <osplay/win/vdd_settings.hpp>

#include <sstream>

namespace osplay::win {
namespace {

std::string xml_escaped(const std::string& text) {
    std::string escaped;
    escaped.reserve(text.size());
    for (const char c : text) {
        switch (c) {
        case '&':
            escaped += "&amp;";
            break;
        case '<':
            escaped += "&lt;";
            break;
        case '>':
            escaped += "&gt;";
            break;
        case '"':
            escaped += "&quot;";
            break;
        case '\'':
            escaped += "&apos;";
            break;
        default:
            escaped += c;
        }
    }
    return escaped;
}

// The driver parses refresh rates with stof(), so "59.94" and "60" both work.
std::string refresh_rate_text(std::uint32_t millihertz) {
    constexpr std::uint32_t kMilli = 1000;
    std::string text = std::to_string(millihertz / kMilli);
    if (const std::uint32_t fraction = millihertz % kMilli; fraction != 0) {
        std::string digits = std::to_string(fraction);
        digits.insert(0, 3 - digits.size(), '0');
        while (digits.back() == '0') {
            digits.pop_back();
        }
        text += "." + digits;
    }
    return text;
}

} // namespace

std::string render_vdd_settings(const helper::MonitorConfig& config) {
    const std::string gpu = config.gpu_name.empty() ? "default" : xml_escaped(config.gpu_name);
    std::ostringstream xml;
    xml << "<?xml version='1.0' encoding='utf-8'?>\n"
        << "<!-- Generated by Osplay. Rewritten before every session; manual edits are lost. -->\n"
        << "<vdd_settings>\n"
        << "    <monitors>\n"
        << "        <count>1</count>\n"
        << "    </monitors>\n"
        << "    <gpu>\n"
        << "        <friendlyname>" << gpu << "</friendlyname>\n"
        << "    </gpu>\n"
        << "    <global>\n"
        << "    </global>\n"
        << "    <resolutions>\n"
        << "        <resolution>\n"
        << "            <width>" << config.width << "</width>\n"
        << "            <height>" << config.height << "</height>\n"
        << "            <refresh_rate>" << refresh_rate_text(config.refresh_millihertz)
        << "</refresh_rate>\n"
        << "        </resolution>\n"
        << "    </resolutions>\n"
        << "    <logging>\n"
        << "        <SendLogsThroughPipe>false</SendLogsThroughPipe>\n"
        << "        <logging>false</logging>\n"
        << "        <debuglogging>false</debuglogging>\n"
        << "    </logging>\n"
        << "    <colour>\n"
        << "        <SDR10bit>false</SDR10bit>\n"
        << "        <HDRPlus>false</HDRPlus>\n"
        << "        <ColourFormat>RGB</ColourFormat>\n"
        << "    </colour>\n"
        // A hardware cursor keeps the pointer out of captured frames; Osplay sends it separately.
        << "    <cursor>\n"
        << "        <HardwareCursor>true</HardwareCursor>\n"
        << "    </cursor>\n"
        << "    <edid>\n"
        << "        <CustomEdid>false</CustomEdid>\n"
        << "    </edid>\n"
        << "</vdd_settings>\n";
    return xml.str();
}

} // namespace osplay::win
